-- Una fila por operación confirmada. La clave la genera el cliente: reenviar la
-- misma no repite la operación, se responde lo que ya quedó registrado.
CREATE TABLE inventario.operaciones (
  clave_idempotencia text PRIMARY KEY,
  tipo text NOT NULL,
  id_usuario integer NOT NULL REFERENCES usuarios.usuarios,
  creada_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE inventario.movimientos (
  id_movimiento bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_variante integer NOT NULL REFERENCES inventario.variantes,
  id_ubicacion smallint NOT NULL REFERENCES inventario.ubicaciones,
  id_ubicacion_destino smallint REFERENCES inventario.ubicaciones,
  id_tipo smallint NOT NULL REFERENCES inventario.tipos_movimiento,
  id_tipo_merma smallint REFERENCES inventario.tipos_merma,
  -- Unidades movidas; en un ajuste es la diferencia aplicada y puede ser negativa.
  cantidad integer NOT NULL,
  fecha timestamptz NOT NULL DEFAULT now(),
  id_usuario integer NOT NULL REFERENCES usuarios.usuarios,
  motivo text NOT NULL CHECK (btrim(motivo) <> ''),
  id_venta bigint,
  -- Un ingreso de varias prendas comparte una misma clave entre sus movimientos.
  clave_idempotencia text REFERENCES inventario.operaciones
);

CREATE INDEX movimientos_por_variante ON inventario.movimientos (id_variante, fecha DESC);
CREATE INDEX movimientos_por_operacion ON inventario.movimientos (clave_idempotencia);

CREATE TABLE inventario.conteos (
  id_conteo bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_variante integer NOT NULL REFERENCES inventario.variantes,
  id_ubicacion smallint NOT NULL REFERENCES inventario.ubicaciones,
  cantidad_sistema integer NOT NULL,
  cantidad_contada integer NOT NULL CHECK (cantidad_contada >= 0),
  id_usuario integer NOT NULL REFERENCES usuarios.usuarios,
  fecha timestamptz NOT NULL DEFAULT now(),
  etapa text NOT NULL DEFAULT 'AJUSTE'
);

-- Tiempo que toma ubicar una prenda. `fin` queda vacío si la búsqueda se canceló.
CREATE TABLE inventario.busquedas (
  id_busqueda bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_variante integer NOT NULL REFERENCES inventario.variantes,
  id_usuario integer NOT NULL REFERENCES usuarios.usuarios,
  inicio timestamptz NOT NULL DEFAULT now(),
  fin timestamptz
);
