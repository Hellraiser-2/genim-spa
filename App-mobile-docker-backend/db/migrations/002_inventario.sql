-- Saldo por variante y ubicación. Debe coincidir con la suma de los movimientos; se
-- mantiene como dato para poder bloquear y validar el stock de forma atómica.
CREATE TABLE inventario.existencias (
  id_variante integer NOT NULL REFERENCES inventario.variantes,
  id_ubicacion smallint NOT NULL REFERENCES inventario.ubicaciones,
  cantidad integer NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
  PRIMARY KEY (id_variante, id_ubicacion)
);

-- Unidades comprometidas en compras del e-commerce que aún no se despachan.
CREATE TABLE inventario.reservas (
  id_reserva bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_venta bigint NOT NULL,
  id_variante integer NOT NULL REFERENCES inventario.variantes,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  estado text NOT NULL CHECK (estado IN ('ACTIVA', 'CONFIRMADA', 'LIBERADA', 'DESPACHADA')),
  -- Solo las reservas ACTIVA vencen; una CONFIRMADA queda firme hasta el despacho.
  expira_en timestamptz
);

CREATE INDEX reservas_vigentes ON inventario.reservas (id_variante) WHERE estado IN ('ACTIVA', 'CONFIRMADA');

CREATE TABLE inventario.tipos_movimiento (
  id_tipo smallint PRIMARY KEY,
  codigo text NOT NULL UNIQUE
);

