-- Esquema de Inventario: catálogo, existencias por ubicación, reservas y movimientos.
--
-- Las columnas `clave` guardan el nombre sin mayúsculas ni tildes (lo calcula el
-- servicio). Su unicidad impide registrar "Metallica" y "metállica" como dos bandas.

CREATE SCHEMA inventario;

CREATE TABLE inventario.tallas (
  id_talla integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  clave text NOT NULL UNIQUE
);

CREATE TABLE inventario.colores (
  id_color integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  clave text NOT NULL UNIQUE
);

CREATE TABLE inventario.bandas (
  id_banda integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  clave text NOT NULL UNIQUE
);

CREATE TABLE inventario.categorias (
  id_categoria integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  clave text NOT NULL UNIQUE,
  -- Las categorías sin banda, como los pantalones, no muestran ese campo.
  usa_banda boolean NOT NULL DEFAULT true,
  -- Zona de la bodega: las letras del código de ubicación "B-<zona>-<posición>".
  zona text NOT NULL UNIQUE,
  -- Última posición entregada en la zona; la siguiente es correlativa.
  ultima_posicion integer NOT NULL DEFAULT 0 CHECK (ultima_posicion >= 0)
);

-- Tallas que admite cada categoría, en el orden en que se ofrecen.
CREATE TABLE inventario.categorias_tallas (
  id_categoria integer NOT NULL REFERENCES inventario.categorias,
  id_talla integer NOT NULL REFERENCES inventario.tallas,
  orden integer NOT NULL,
  PRIMARY KEY (id_categoria, id_talla)
);

CREATE TABLE inventario.productos (
  id_producto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria integer NOT NULL REFERENCES inventario.categorias,
  id_banda integer REFERENCES inventario.bandas,
  codigo_ubicacion text NOT NULL UNIQUE,
  nombre text NOT NULL CHECK (btrim(nombre) <> ''),
  clave text NOT NULL UNIQUE,
  descripcion text,
  imagen_url text,
  -- El precio y el costo los define el Gerente; un producto recién creado desde bodega aún no los tiene.
  precio integer CHECK (precio >= 0),
  costo_compra integer CHECK (costo_compra >= 0),
  peso_gramos integer CHECK (peso_gramos > 0),
  alto_cm integer CHECK (alto_cm > 0),
  ancho_cm integer CHECK (ancho_cm > 0),
  largo_cm integer CHECK (largo_cm > 0),
  activo boolean NOT NULL DEFAULT true
);

CREATE TABLE inventario.variantes (
  id_variante integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto integer NOT NULL REFERENCES inventario.productos,
  id_talla integer NOT NULL REFERENCES inventario.tallas,
  id_color integer NOT NULL REFERENCES inventario.colores,
  sku text NOT NULL UNIQUE,
  codigo text NOT NULL UNIQUE,
  activo boolean NOT NULL DEFAULT true,
  UNIQUE (id_producto, id_talla, id_color)
);

CREATE TABLE inventario.ubicaciones (
  id_ubicacion smallint PRIMARY KEY,
  nombre text NOT NULL UNIQUE
);

